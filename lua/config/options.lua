-- Habilita suporte a cores RGB (necessário para temas modernos como catppuccin)
vim.opt.termguicolors = true

-- Usa espaços ao invés de um caractere tab real ao pressionar Tab
vim.opt.expandtab = true

-- Tamanho visual de um tab (quantos espaços ele ocupa na tela)
vim.opt.tabstop = 2

-- Tamanho ao pressionar Tab no insert mode
vim.opt.softtabstop = 2

-- Tamanho da indentação ao usar >> ou << no modo normal
vim.opt.shiftwidth = 2

-- Define a tecla líder como espaço (usada em atalhos como <leader>fg e <leader>e)
vim.g.mapleader = " "
